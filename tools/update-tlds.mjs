// Writes apps/demo/src/tlds.ts from IANA's list of the top level domains of the root zone, which
// the address bar needs to tell an address (example.com) from a search (node.js) like Chrome.
//
//   node tools/update-tlds.mjs
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { root } from './pins.mjs';

const SOURCE = 'https://data.iana.org/TLD/tlds-alpha-by-domain.txt';
const target = path.join(root, 'apps/demo/src/tlds.ts');

const response = await fetch(SOURCE);
if (!response.ok) throw new Error(`${SOURCE}: HTTP ${response.status}`);
const lines = (await response.text()).split('\n');
const version = /^# Version (\d+)/.exec(lines[0] ?? '')?.[1];
const names = lines
  .filter((line) => line && !line.startsWith('#'))
  .map((line) => line.trim().toLowerCase());
if (!version || names.length < 1000 || names.some((name) => !/^[a-z0-9-]+$/.test(name)))
  throw new Error(`${SOURCE}: not the expected list`);

// Lines of at most 100 characters (Biome's width) in a template literal
const rows = [];
for (const name of names) {
  const last = rows.length - 1;
  if (last >= 0 && rows[last].length + name.length + 1 <= 98) rows[last] += ` ${name}`;
  else rows.push(name);
}
writeFileSync(
  target,
  `// Generated by tools/update-tlds.mjs from IANA's list of top level domains, version ${version}.

/** The top level domains of the root zone in lower case, internationalized ones as xn--. */
export const TOP_LEVEL_DOMAINS: ReadonlySet<string> = new Set(
  \`
${rows.join('\n')}
\`
    .trim()
    .split(/\\s+/),
);
`,
);
console.log(
  `${path.relative(root, target)}: ${names.length} top level domains, version ${version}`,
);
